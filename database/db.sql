-- =============================================================================
-- CTRL — Database schema + seed data
-- The tables are created by SQLAlchemy models (authoritative), and this file's
-- INSERTs are executed by database/init_db.py to seed data. It is also valid to
-- run this whole file directly (e.g. `mysql < database/db.sql`).
-- Charset utf8mb4 is required for full i18n (Arabic, emoji, etc.).
-- =============================================================================

CREATE DATABASE IF NOT EXISTS `ctrl`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `ctrl`;

-- Roles: Cashier < Moderator < Admin < SuperAdmin ----------------------------
CREATE TABLE IF NOT EXISTS `roles` (
  `id`          INT AUTO_INCREMENT PRIMARY KEY,
  `name`        VARCHAR(50)  NOT NULL UNIQUE,
  `level`       INT          NOT NULL DEFAULT 0,
  `description` VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Users: username + bcrypt password hash --------------------------------------
CREATE TABLE IF NOT EXISTS `users` (
  `id`                   INT AUTO_INCREMENT PRIMARY KEY,
  `username`             VARCHAR(100) NOT NULL UNIQUE,
  `full_name`            VARCHAR(150) NULL,
  `password_hash`        VARCHAR(255) NOT NULL,
  `is_active`            TINYINT(1)   NOT NULL DEFAULT 1,
  `must_reset_password`  TINYINT(1)   NOT NULL DEFAULT 1,
  `locale`               VARCHAR(10)  NOT NULL DEFAULT 'en',
  `role_id`              INT          NOT NULL,
  `created_at`           DATETIME     DEFAULT CURRENT_TIMESTAMP,
  `updated_at`           DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_users_role` FOREIGN KEY (`role_id`) REFERENCES `roles`(`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Action logs: every meaningful action ---------------------------------------
CREATE TABLE IF NOT EXISTS `action_logs` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `user_id`    INT          NULL,
  `action`     VARCHAR(100) NOT NULL,
  `entity`     VARCHAR(100) NULL,
  `entity_id`  VARCHAR(100) NULL,
  `details`    TEXT         NULL,
  `status`     VARCHAR(20)  NOT NULL DEFAULT 'success',
  `ip_address` VARCHAR(64)  NULL,
  `user_agent` VARCHAR(255) NULL,
  `created_at` DATETIME     DEFAULT CURRENT_TIMESTAMP,
  KEY `idx_logs_user` (`user_id`),
  KEY `idx_logs_action` (`action`),
  KEY `idx_logs_created` (`created_at`),
  CONSTRAINT `fk_logs_user` FOREIGN KEY (`user_id`)
    REFERENCES `users`(`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Translations: backend-managed i18n (en, ar, + future locales) ---------------
CREATE TABLE IF NOT EXISTS `translations` (
  `id`        INT AUTO_INCREMENT PRIMARY KEY,
  `namespace` VARCHAR(100) NOT NULL DEFAULT 'common',
  `key`       VARCHAR(150) NOT NULL,
  `locale`    VARCHAR(10)  NOT NULL,
  `value`     TEXT         NOT NULL,
  UNIQUE KEY `uq_translation` (`namespace`, `key`, `locale`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Settings: DB-configurable app settings (brand, currency, ...) ---------------
CREATE TABLE IF NOT EXISTS `settings` (
  `key`   VARCHAR(100) PRIMARY KEY,
  `value` TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Categories: bilingual (en/ar), extensible to more locales -------------------
-- Images stored as base64 directly in the DB (no filesystem folder) -----------
CREATE TABLE IF NOT EXISTS `images` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `data`       LONGTEXT     NOT NULL,
  `mime`       VARCHAR(100) NOT NULL DEFAULT 'image/png',
  `created_at` DATETIME     DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `categories` (
  `id`          INT AUTO_INCREMENT PRIMARY KEY,
  `name_en`     VARCHAR(120) NOT NULL,
  `name_ar`     VARCHAR(120) NOT NULL,
  `description` TEXT         NULL,
  `image_id`    INT          NULL,
  `is_active`   TINYINT(1)   NOT NULL DEFAULT 1,
  CONSTRAINT `fk_categories_image` FOREIGN KEY (`image_id`)
    REFERENCES `images`(`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Suppliers -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `suppliers` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `name`       VARCHAR(180) NOT NULL,
  `phone`      VARCHAR(60)  NULL,
  `email`       VARCHAR(180) NULL,
  `address`     TEXT         NULL,
  `is_deleted`  TINYINT(1)   NOT NULL DEFAULT 0,
  `created_at`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Supplier invoices -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS `supplier_invoices` (
  `id`          INT AUTO_INCREMENT PRIMARY KEY,
  `supplier_id` INT           NOT NULL,
  `name`         VARCHAR(255)  NOT NULL,
  `quantity`     INT           NOT NULL DEFAULT 0,
  `amount`       DECIMAL(12,2) NOT NULL DEFAULT 0,
  `invoice_date` DATE          NULL,
  `image_url`    VARCHAR(512)  NULL,
  `created_at`  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT `fk_invoice_supplier` FOREIGN KEY (`supplier_id`)
    REFERENCES `suppliers` (`id`) ON DELETE CASCADE,
  INDEX `ix_invoice_supplier` (`supplier_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Attribute definitions (Color, Size, ...) -----------------------------------
CREATE TABLE IF NOT EXISTS `attributes` (
  `id`          INT AUTO_INCREMENT PRIMARY KEY,
  `key`         VARCHAR(60)  NOT NULL UNIQUE,
  `type`        VARCHAR(20)  NOT NULL DEFAULT 'text',
  `name_en`     VARCHAR(120) NOT NULL,
  `name_ar`     VARCHAR(120) NOT NULL,
  `is_required` TINYINT(1)   NOT NULL DEFAULT 0,
  -- Global: one value shared across the whole product (coding requires NOT global).
  `is_global`   TINYINT(1)   NOT NULL DEFAULT 0,
  `coding`      TINYINT(1)   NOT NULL DEFAULT 0,
  `sort_order`  INT DEFAULT 0,
  `is_active`   TINYINT(1)   NOT NULL DEFAULT 1,
  `is_deleted`  TINYINT(1)   NOT NULL DEFAULT 0,
  `deleted_at`  DATETIME     NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `attribute_values` (
  `id`           INT AUTO_INCREMENT PRIMARY KEY,
  `attribute_id` INT NOT NULL,
  `value_en`     VARCHAR(120) NOT NULL,
  `value_ar`     VARCHAR(120) NOT NULL,
  `extra`        JSON NULL,
  `sort_order`   INT DEFAULT 0,
  `is_deleted`   TINYINT(1)   NOT NULL DEFAULT 0,
  KEY `idx_attrval_attr` (`attribute_id`),
  CONSTRAINT `fk_attrval_attr` FOREIGN KEY (`attribute_id`)
    REFERENCES `attributes`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Products (shared info) ------------------------------------------------------
-- Prices are float. `tags` is JSON. Deletion is a SOFT delete.
CREATE TABLE IF NOT EXISTS `products` (
  `id`                INT AUTO_INCREMENT PRIMARY KEY,
  `code`              VARCHAR(32)  NOT NULL,
  `name`              VARCHAR(255) NOT NULL,
  `description`       TEXT         NULL,
  `category_id`       INT          NULL,
  `supplier_id`       INT          NULL,
  `supplier_price`    DECIMAL(12,2) DEFAULT 0,
  `min_price`         DECIMAL(12,2) DEFAULT 0,
  `price`             DECIMAL(12,2) DEFAULT 0,
  `note`              TEXT         NULL,
  `tags`              JSON         NULL,
  `attributes`        JSON         NULL,
  `is_deleted`        TINYINT(1)   NOT NULL DEFAULT 0,
  `deleted_at`        DATETIME     NULL,
  `created_at`        DATETIME     DEFAULT CURRENT_TIMESTAMP,
  `updated_at`        DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uq_products_code` (`code`),
  KEY `idx_products_deleted` (`is_deleted`),
  CONSTRAINT `fk_products_category` FOREIGN KEY (`category_id`) REFERENCES `categories`(`id`),
  CONSTRAINT `fk_products_supplier` FOREIGN KEY (`supplier_id`) REFERENCES `suppliers`(`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Product variants = CODE UNITS (one per coding-attribute combo) --------------
-- Owns the unique code + images. `attributes` is JSON {attr_id: value_id} of the
-- CODING attributes only. `quantity` is legacy (on-hand now lives per stock unit).
CREATE TABLE IF NOT EXISTS `product_variants` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `product_id` INT NOT NULL,
  `code`       VARCHAR(32) NOT NULL UNIQUE,
  `attributes` JSON NULL,
  `quantity`   INT NOT NULL DEFAULT 0,
  `is_deleted` TINYINT(1) NOT NULL DEFAULT 0,
  `deleted_at` DATETIME NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY `idx_variant_product` (`product_id`),
  KEY `idx_variant_code` (`code`),
  CONSTRAINT `fk_variant_product` FOREIGN KEY (`product_id`)
    REFERENCES `products`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Variant stock units = sellable SKUs (non-global, non-coding attr combos) ------
-- `attributes` is JSON {attr_id: value_id} of the non-global, non-coding
-- attributes; `quantity` is the on-hand count for that exact combination.
CREATE TABLE IF NOT EXISTS `product_variant_stocks` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `variant_id` INT NOT NULL,
  `attributes` JSON NULL,
  `quantity`   INT NOT NULL DEFAULT 0,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY `idx_stock_variant` (`variant_id`),
  CONSTRAINT `fk_stock_variant` FOREIGN KEY (`variant_id`)
    REFERENCES `product_variants`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Product images (up to 5 per variant) ----------------------------------------
CREATE TABLE IF NOT EXISTS `product_images` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `variant_id` INT NOT NULL,
  `url`        VARCHAR(512) NOT NULL,
  `sort_order` INT DEFAULT 0,
  KEY `idx_pimg_variant` (`variant_id`),
  CONSTRAINT `fk_pimg_variant` FOREIGN KEY (`variant_id`)
    REFERENCES `product_variants`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Point of Sale: customers, payment methods, sales, holds ---------------------
CREATE TABLE IF NOT EXISTS `customers` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `phone`      VARCHAR(40)  NULL UNIQUE,
  `name`       VARCHAR(180) NOT NULL,
  `created_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `payment_methods` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `code`       VARCHAR(40) NOT NULL UNIQUE,
  `name_en`    VARCHAR(80) NOT NULL,
  `name_ar`    VARCHAR(80) NOT NULL,
  `is_active`  TINYINT(1)  NOT NULL DEFAULT 1,
  `sort_order` INT         NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `sales` (
  `id`                INT AUTO_INCREMENT PRIMARY KEY,
  `invoice_no`        VARCHAR(32) NOT NULL UNIQUE,
  `user_id`           INT NULL,
  `customer_id`       INT NULL,
  `payment_method_id` INT NULL,
  `item_count`        INT           NOT NULL DEFAULT 0,
  `subtotal`          DECIMAL(12,2) NOT NULL DEFAULT 0,
  `discount`          DECIMAL(12,2) NOT NULL DEFAULT 0,
  `total`             DECIMAL(12,2) NOT NULL DEFAULT 0,
  `paid_amount`       DECIMAL(12,2) NOT NULL DEFAULT 0,
  `change_amount`     DECIMAL(12,2) NOT NULL DEFAULT 0,
  `change_raw`        DECIMAL(12,2) NOT NULL DEFAULT 0,
  `created_at`        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY `idx_sales_user` (`user_id`),
  KEY `idx_sales_customer` (`customer_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `sale_items` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `sale_id`    INT NOT NULL,
  `product_id` INT NULL,
  `variant_id` INT NULL,
  `stock_id`   INT NULL,
  `code`       VARCHAR(32)  NOT NULL,
  `name`       VARCHAR(255) NOT NULL,
  `attributes` JSON NULL,
  `unit_price` DECIMAL(12,2) NOT NULL DEFAULT 0,
  `list_price` DECIMAL(12,2) NOT NULL DEFAULT 0,
  `min_price`  DECIMAL(12,2) NOT NULL DEFAULT 0,
  `quantity`   INT           NOT NULL DEFAULT 0,
  `line_total` DECIMAL(12,2) NOT NULL DEFAULT 0,
  KEY `idx_sitem_sale` (`sale_id`),
  KEY `idx_sitem_variant` (`variant_id`),
  KEY `idx_sitem_stock` (`stock_id`),
  CONSTRAINT `fk_sitem_sale` FOREIGN KEY (`sale_id`)
    REFERENCES `sales`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Holds reserve a STOCK unit (per cashier tab). Transient (2h TTL).
CREATE TABLE IF NOT EXISTS `sale_holds` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `hold_key`   VARCHAR(64) NOT NULL,
  `stock_id`   INT NOT NULL,
  `quantity`   INT NOT NULL DEFAULT 0,
  `flexible`   TINYINT(1) NOT NULL DEFAULT 0,
  `user_id`    INT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uq_hold_key_stock` (`hold_key`, `stock_id`),
  KEY `idx_hold_key` (`hold_key`),
  KEY `idx_hold_stock` (`stock_id`),
  CONSTRAINT `fk_hold_stock` FOREIGN KEY (`stock_id`)
    REFERENCES `product_variant_stocks`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

